import { spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

function waitForServer(url, timeoutMs = 15000) {
  const start = Date.now();
  return new Promise((resolve, reject) => {
    const attempt = () => {
      const req = http.get(url, (res) => {
        res.resume();
        resolve();
      });
      req.on('error', () => {
        if (Date.now() - start > timeoutMs) {
          reject(new Error(`Timed out waiting for preview server at ${url}`));
        } else {
          setTimeout(attempt, 250);
        }
      });
    };
    attempt();
  });
}

function buildMarkdownReport(data) {
  const dimRows = Object.entries(data.dimensions)
    .map(([name, score]) => `| ${name} | **${score} / 10** | ${score === 10 ? 'PASS' : 'NEEDS FIX'} |`)
    .join('\n');

  const findingsSection =
    data.findings.length === 0
      ? '_Zero automated UI coherence defects detected across all tested routes, viewports, and themes._'
      : data.findings.map((f) => `- ${f}`).join('\n');

  return `# Cognify UI Coherence & Polish Scorecard

> Auto-generated by \`npm run audit:ui\`. Audits Desktop (1366×900) and Mobile (390×844) across both Light and Dark modes on 18 core routes (${data.statesAudited} total rendered page states).

## Overall Score: **${data.score} / 100**

| Dimension | Score | Status |
| --- | ---: | --- |
${dimRows}

## Detected Issues (${data.findings.length})

${findingsSection}
`;
}

async function main() {
  const args = process.argv.slice(2);
  const writeReport = args.includes('--write-report');
  const screenshotsIdx = args.indexOf('--screenshots');
  const screenshotsDir =
    screenshotsIdx !== -1 && args[screenshotsIdx + 1] ? args[screenshotsIdx + 1] : '';
  const port = 4197;
  const baseUrl = `http://127.0.0.1:${port}`;

  if (!fs.existsSync(path.join(ROOT_DIR, 'dist', 'index.html'))) {
    console.log('[audit:ui] dist/ not found — building production bundle first...');
    const buildRes = spawnSync('npm', ['run', 'build'], { cwd: ROOT_DIR, stdio: 'inherit' });
    if (buildRes.status !== 0) process.exit(buildRes.status ?? 1);
  }

  const server = spawn(
    'npx',
    ['vite', 'preview', '--host', '127.0.0.1', '--port', String(port), '--strictPort'],
    { cwd: ROOT_DIR, stdio: 'ignore' }
  );

  const jsonTmp = path.join('/tmp', `cognify-ui-audit-${process.pid}.json`);

  try {
    await waitForServer(`${baseUrl}/`);
    const pyArgs = [
      path.join(ROOT_DIR, 'scripts', 'audit_ui_coherence.py'),
      '--base-url',
      baseUrl,
      '--json-out',
      jsonTmp,
    ];
    if (screenshotsDir) {
      pyArgs.push('--screenshots-dir', screenshotsDir);
    }

    const res = spawnSync('python3', pyArgs, { cwd: ROOT_DIR, encoding: 'utf8' });
    if (res.status !== 0) {
      console.error(res.stderr || res.stdout);
      process.exit(res.status ?? 1);
    }

    const data = JSON.parse(fs.readFileSync(jsonTmp, 'utf8'));
    console.log(`\n=== Cognify UI Coherence & Polish Audit ===`);
    console.log(`Overall UI Score: ${data.score}/100 across ${data.statesAudited} states`);
    for (const [dim, pts] of Object.entries(data.dimensions)) {
      console.log(`  ${dim.padEnd(44)} ${String(pts).padStart(2)}/10`);
    }
    if (data.findings.length > 0) {
      console.log(`\nFindings (${data.findings.length}):`);
      for (const f of data.findings) {
        console.log(`  - ${f}`);
      }
    } else {
      console.log(`\nZero UI defects detected!`);
    }

    if (writeReport) {
      const reportPath = path.join(ROOT_DIR, 'docs', 'UI_POLISH_REPORT.md');
      fs.writeFileSync(reportPath, buildMarkdownReport(data), 'utf8');
      console.log(`\nUpdated docs/UI_POLISH_REPORT.md`);
    }
  } finally {
    server.kill('SIGTERM');
    if (fs.existsSync(jsonTmp)) fs.unlinkSync(jsonTmp);
  }
}

main().catch((err) => {
  console.error('[audit:ui] Error:', err);
  process.exit(1);
});
