export function getOfficialCambridgePapersForCourse(
  qualification: string,
  subjectSlug: string,
  board?: string
): OfficialCambridgeSubjectPapers | undefined {
  const key = `${qualification}-${subjectSlug}`;
  if (OFFICIAL_CAMBRIDGE_PAPERS[key]) return OFFICIAL_CAMBRIDGE_PAPERS[key];
  if (qualification === 'gcse' && board === 'cie') {
    return OFFICIAL_CAMBRIDGE_PAPERS[`igcse-${subjectSlug}`];
  }
  return undefined;
}
